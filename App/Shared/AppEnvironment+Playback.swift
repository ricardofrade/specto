/// Background audio, Now Playing, audio mode, SponsorBlock and DeArrow: every platform.
extension AppEnvironment {
    func startSystemIntegration() {
        #if os(iOS)
        observeAudioRoute()
        followEngineForPictureInPicture()
        #endif
    }

    /// The audio session and Now Playing / remote commands, set up on the first playback rather
    /// than at launch (about 13 ms of main-thread time off the path to the first frame).
    func prepareForPlayback() {
        guard nowPlaying == nil else { return }
        NowPlayingController.configureAudioSession()
        nowPlaying = NowPlayingController(session: session) { url in
            await ImagePipeline.shared.image(url, pixelSize: CGSize(width: 600, height: 600))
        }
    }

    // MARK: Background

    /// Background without PiP: keep audio, stop decoding video. Back to the foreground: resume.
    func scenePhaseChanged(_ phase: ScenePhase) {
        switch phase {
        case .background where !isPictureInPictureActive:
            session.setVideoEnabled(false)
            HomeSnapshotPublisher.publish(database)
        case .background:
            HomeSnapshotPublisher.publish(database)
        case .active:
            session.setVideoEnabled(true)
            #if os(iOS)
            systemPictureInPicture.stop()
            #endif
            Task { await syncNow() }
        default:
            break
        }
    }

    private var isPictureInPictureActive: Bool {
        #if os(iOS)
        pictureInPicture.isActive || systemPictureInPicture.isActive || systemPictureInPicture.isStarting
        #else
        false
        #endif
    }

    // MARK: Audio mode

    func switchMode(to mode: PlaybackMode) async {
        guard let page = currentPage, let request = try? plan(page, mode: mode, startAt: session.position) else { return }
        await session.switchMode(to: mode, using: request)
        if let id = session.item?.videoID { loadSelectedCaption(for: id) }
    }

    // MARK: Subtitles

    /// Picks the remembered language (else, with the system's Closed Captions setting on, the
    /// device language), preferring human-made subtitles over auto-generated ones.
    func applyCaptions(_ tracks: [CaptionTrack], for id: VideoID) {
        captionTracks = tracks
        let remembered = AppSettings.shared.captionLanguage
        let language = remembered == "off" ? nil
            : remembered ?? (MACaptionAppearanceGetDisplayType(.user) == .alwaysOn
                             ? Locale.current.language.languageCode?.identifier : nil)
        selectedCaption = language.flatMap { Self.bestTrack(in: tracks, language: $0) }
        loadSelectedCaption(for: id)
    }

    /// From the player's menu; remembered for the next video.
    func selectCaption(_ track: CaptionTrack?) {
        AppSettings.shared.captionLanguage = track.map { Self.languageCode($0.language) } ?? "off"
        selectedCaption = track
        if let id = session.item?.videoID { loadSelectedCaption(for: id) }
    }

    /// The captions button: off, or back on in the remembered language (else the first track).
    func toggleCaptions() {
        if selectedCaption != nil {
            selectCaption(nil)
        } else {
            let remembered = AppSettings.shared.captionLanguage.flatMap { $0 == "off" ? nil : $0 }
            selectCaption(remembered.flatMap { Self.bestTrack(in: captionTracks, language: $0) } ?? captionTracks.first)
        }
    }

    func loadSelectedCaption(for id: VideoID) {
        guard let track = selectedCaption else {
            session.setSubtitles([], for: id)
            return
        }
        Task {
            let cues = await Task.detached(priority: .userInitiated) { () -> [SubtitleCue] in
                guard let (data, _) = try? await URLSession.shared.data(from: track.url),
                      let text = String(data: data, encoding: .utf8) else { return [] }
                return WebVTT.parse(text)
            }.value
            if selectedCaption == track { session.setSubtitles(cues, for: id) }
        }
    }

    static func bestTrack(in tracks: [CaptionTrack], language: String) -> CaptionTrack? {
        tracks.filter { languageCode($0.language) == language }
            .sorted { !$0.isAutoGenerated && $1.isAutoGenerated }
            .first
    }

    /// "en-US" → "en".
    static func languageCode(_ tag: String) -> String {
        String(tag.prefix { $0 != "-" && $0 != "_" }).lowercased()
    }

    // MARK: SponsorBlock and DeArrow

    func loadSkipSegments(for id: VideoID) {
        guard AppSettings.shared.skipsSponsors, !id.isPeerTube else { return }   // SponsorBlock knows YouTube only.
        let community = self.community
        let actions = AppSettings.shared.sponsorActions
        let categories = Set(actions.filter { $0.value != .off }.keys)
        let manual = Set(actions.filter { $0.value == .ask }.keys)
        let shownOnly = Set(actions.filter { $0.value == .show }.keys)
        Task {
            if let segments = try? await community.skipSegments(for: id, categories: categories) {
                session.setSkipSegments(segments, for: id, manual: manual, shownOnly: shownOnly)
            }
        }
    }

    func refreshBranding() {
        guard AppSettings.shared.brandedTitles || AppSettings.shared.brandedThumbnails else { return }
        let store = BrandingStore(database), community = self.community
        Task.detached(priority: .utility) {
            // DeArrow knows YouTube's videos only.
            guard let ids = try? store.videosNeedingLookup().filter({ !$0.isPeerTube }), !ids.isEmpty,
                  let branding = try? await community.branding(for: ids) else { return }
            try? store.save(branding, lookedUp: ids)
        }
    }

    /// What to tell the viewer when a video can't play.
    static func message(for error: Error) -> String {
        switch error {
        case SourceError.unavailable(let reason):
            reason ?? String(localized: "This video isn't available.")
        case SourceError.blockedUpstream:
            String(localized: "Your instances are being blocked by YouTube right now. Try again later.")
        case SourceError.unsupported:
            String(localized: "None of your instances can play videos.")
        case let error as PlaybackError:
            switch error {
            case .unsupportedFormat(let detail): detail
            default: String(localized: "Playback failed.")
            }
        default:
            String(localized: "Couldn't load this video.")
        }
    }

    static func seconds(_ duration: Duration) -> Double {
        Double(duration.components.seconds) + Double(duration.components.attoseconds) / 1e18
    }
}
