import Foundation
import Testing
@testable import Core

/// Decoding against responses recorded from a real Invidious instance (hosts sanitised).
struct InvidiousSourceTests {
    private func source(_ setup: (FixtureClient) -> Void) -> InvidiousSource {
        let client = FixtureClient()
        setup(client)
        return InvidiousSource(instance: instance(.invidious), client: client)
    }

    @Test func parsesCodecsFromTheMimeTypeEvenWithoutContainer() async throws {
        let iv = source { $0.on("/api/v1/videos/dQw4w9WgXcQ", fixture: "invidious/video.json") }
        let manifest = try await iv.watchPage(for: VideoID(rawValue: "dQw4w9WgXcQ")).manifest

        // itag 399 has no `container`/`encoding` in Invidious's table; the MIME type still says AV1 in MP4.
        #expect(manifest.videoStreams.map(\.itag) == [137, 399])
        let av1 = try #require(manifest.videoStreams.last)
        #expect(av1.codec == .av1 && av1.container == .mp4 && av1.codecs == "av01.0.08M.08")
        #expect(av1.initRange == ByteRange(start: 0, end: 699) && av1.indexRange == ByteRange(start: 700, end: 1187))
        #expect(av1.width == 1920 && av1.height == 1080)

        let aac = try #require(manifest.audioStreams.first)
        #expect(aac.codec == .aac && aac.itag == 140 && aac.indexRange == ByteRange(start: 723, end: 1018))
    }

    @Test func captionURLsBecomeAbsoluteOnTheInstance() async throws {
        let iv = source { $0.on("/api/v1/videos/dQw4w9WgXcQ", fixture: "invidious/video.json") }
        let captions = try await iv.watchPage(for: VideoID(rawValue: "dQw4w9WgXcQ")).manifest.captions
        #expect(captions.first?.url.absoluteString == "https://instance.example/api/v1/captions/dQw4w9WgXcQ?label=English")
        #expect(captions.contains { $0.isAutoGenerated })
    }

    @Test func dubbedTracksAreNotOriginalAndDRCCopiesAreDropped() async throws {
        let iv = source { $0.on("/api/v1/videos/multi", fixture: "invidious/video-multiaudio.json") }
        let audio = try await iv.watchPage(for: VideoID(rawValue: "multi")).manifest.audioStreams
        #expect(audio.count == 2)
        #expect(audio.map(\.language) == ["en", "ar"])
        #expect(audio.map(\.isOriginal) == [true, false])
    }

    @Test func hdrComesFromTheTransferCharacteristics() async throws {
        let iv = source { $0.on("/api/v1/videos/hdr", fixture: "invidious/video-hdr.json") }
        let video = try await iv.watchPage(for: VideoID(rawValue: "hdr")).manifest.videoStreams
        #expect(video.count == 2)
        #expect(video.allSatisfy { $0.isHDR })
        #expect(video.map(\.codec) == [.vp9, .av1])
    }

    @Test func channelFeedComesFromAtomWithExactDates() async throws {
        let iv = source { $0.on("/feed/channel/", fixture: "invidious/channel-feed.xml") }
        let feed = try await iv.feed(for: [ChannelID(rawValue: "UCuAXFkgsw1L7xaCfnd5JJOw")])
        #expect(feed.count == 3)
        #expect(feed.allSatisfy { $0.publishedAt != nil && $0.channelID.rawValue == "UCuAXFkgsw1L7xaCfnd5JJOw" })
        #expect(feed.allSatisfy { !$0.title.isEmpty && !$0.thumbnails.isEmpty })
    }

    @Test func oneMissingChannelDoesNotFailTheFeed() async throws {
        let client = FixtureClient()
        client.on("/feed/channel/UCgood", fixture: "invidious/channel-feed.xml")
        client.on("/feed/channel/UCgone", status: 404, body: Data(#"{"error":"Channel does not exist."}"#.utf8))
        let iv = InvidiousSource(instance: instance(.invidious), client: client)
        let feed = try await iv.feed(for: [ChannelID(rawValue: "UCgood"), ChannelID(rawValue: "UCgone")])
        #expect(feed.count == 3)
    }

    @Test func channelPlaylistsComeWithInstanceThumbnails() async throws {
        let iv = source { $0.on("/playlists", fixture: "invidious/channel-playlists.json") }
        let page = try await iv.channelPlaylists(ChannelID(rawValue: "UCSMOQeBJ2RAnuFungnQOxLg"), cursor: nil)
        #expect(page.items.count == 3)
        let first = try #require(page.items.first)
        #expect(first.id.rawValue.hasPrefix("PL"))
        #expect(!first.title.isEmpty && first.videoCount ?? 0 > 0)
        #expect(first.channelName == nil)   // Invidious says "Playlist" here.
        // Never i.ytimg.com: the instance serves the same image.
        #expect(page.items.allSatisfy { $0.thumbnails.allSatisfy { $0.url.host() == "instance.example" } })
        #expect(first.thumbnails.first?.url.path().hasSuffix("/mqdefault.jpg") == true)
        #expect(page.nextCursor != nil)
    }

    @Test func playlistCursorIsTheNextIndex() async throws {
        let iv = source { $0.on("/api/v1/playlists/", fixture: "invidious/playlist.json") }
        let page = try await iv.playlist(PlaylistID(rawValue: "PL"), cursor: nil)
        #expect(page.videoCount == 182)
        #expect(page.videos.items.count == 3)
        #expect(page.videos.nextCursor == "3")
    }

    @Test func errorsMapToRoutingDecisions() {
        let missing = InvidiousSource.mapError(status: 404, body: FixtureClient.fixture("invidious/error-video-unavailable.json"))
        guard case .unavailable = missing else { Issue.record("Got \(missing)"); return }
        let bot = InvidiousSource.mapError(status: 500, body: Data(#"{"error":"Sign in to confirm you're not a bot"}"#.utf8))
        guard case .blockedUpstream = bot else { Issue.record("Got \(bot)"); return }
        #expect(bot.isRetryableElsewhere && !missing.isRetryableElsewhere)
    }
}
